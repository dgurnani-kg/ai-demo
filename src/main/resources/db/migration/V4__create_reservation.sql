CREATE TABLE reservation (
    id          BIGINT                   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     BIGINT                   NOT NULL,
    member_id   BIGINT                   NOT NULL,
    status      VARCHAR(16)              NOT NULL,
    reserved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ready_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_reservation_book   FOREIGN KEY (book_id)   REFERENCES book (id),
    CONSTRAINT fk_reservation_member FOREIGN KEY (member_id) REFERENCES library_member (id)
);

CREATE INDEX idx_reservation_queue ON reservation (book_id, status, reserved_at);
